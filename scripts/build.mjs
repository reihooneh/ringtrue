// Builds the site from its sources:
//   src/pages/*.html + the shared layout   ->  site/*.html
//   the C++ wood table and a default set   ->  site/assets/js/materials.js, presets.js
//   three.js and the fonts (pinned npm)    ->  site/assets/vendor, site/assets/fonts
// Needs the native command line tool first (make cli). CI checks the output is up to date.
import { execFileSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cli = join(root, 'build', 'ringtrue');
const run = (...args) => execFileSync(cli, args, { encoding: 'utf8', maxBuffer: 1 << 24 });

// ---------- Generated data ----------
const banner = (what) => `// Generated by scripts/build.mjs from ${what}. Do not edit by hand.\n`;
const materials = JSON.parse(run('materials', '--json'));
writeFileSync(join(root, 'site/assets/js/materials.js'), `${banner('core/materials.hpp')}export const MATERIALS = ${JSON.stringify(materials, null, 1)};\n`);

let set;
try {
  set = JSON.parse(run('set', '--from', 'C4', '--to', 'C6', '--json'));
} catch (err) {
  // Exit code 1 means some upper partials missed; the JSON is still complete.
  if (err.status !== 1) throw err;
  set = JSON.parse(err.stdout);
}
writeFileSync(
  join(root, 'site/assets/js/presets.js'),
  `${banner('`ringtrue set --from C4 --to C6`')}export const DEFAULT_SET = ${JSON.stringify({ wood: 'rosewood', bars: set })};\n`,
);

// ---------- Vendored files ----------
const copies = [
  ['node_modules/three/build/three.module.min.js', 'site/assets/vendor/three.module.min.js'],
  ['node_modules/three/LICENSE', 'site/assets/vendor/three.LICENSE.txt'],
  ['node_modules/@fontsource-variable/bricolage-grotesque/files/bricolage-grotesque-latin-standard-normal.woff2', 'site/assets/fonts/bricolage-grotesque-latin.woff2'],
  ['node_modules/@fontsource-variable/bricolage-grotesque/LICENSE', 'site/assets/fonts/bricolage-grotesque.LICENSE.txt'],
  ['node_modules/@fontsource-variable/newsreader/files/newsreader-latin-opsz-normal.woff2', 'site/assets/fonts/newsreader-latin.woff2'],
  ['node_modules/@fontsource-variable/newsreader/files/newsreader-latin-opsz-italic.woff2', 'site/assets/fonts/newsreader-latin-italic.woff2'],
  ['node_modules/@fontsource-variable/newsreader/LICENSE', 'site/assets/fonts/newsreader.LICENSE.txt'],
];
for (const [from, to] of copies) {
  mkdirSync(dirname(join(root, to)), { recursive: true });
  copyFileSync(join(root, from), join(root, to));
}

// ---------- Pages ----------
const CSP = [
  "default-src 'none'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "worker-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "media-src 'self' blob: mediastream:",
  "base-uri 'none'",
  "form-action 'none'",
].join('; ');
const NAV = [
  ['index', 'index.html', 'Home'],
  ['design', 'design.html', 'Design a bar'],
  ['workshop', 'workshop.html', 'Tune a bar'],
  ['set', 'set.html', 'Play a set'],
  ['method', 'method.html', 'How it works'],
];
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const pagesDir = join(root, 'src/pages');
const built = [];
for (const file of readdirSync(pagesDir).filter((f) => f.endsWith('.html')).sort()) {
  const raw = readFileSync(join(pagesDir, file), 'utf8');
  const m = raw.match(/^<!--(\{[\s\S]*?\})-->\n/);
  if (!m) throw new Error(`${file}: missing the JSON header comment`);
  const meta = JSON.parse(m[1]);
  const body = raw.slice(m[0].length);
  const nav = NAV.map(
    ([id, href, label]) => `<a href="${href}"${id === meta.nav ? ' aria-current="page"' : ''}>${label}</a>`,
  ).join('\n        ');
  const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta http-equiv="Content-Security-Policy" content="${CSP}">
  <meta name="referrer" content="no-referrer">
  <title>${esc(meta.title)}</title>
  <meta name="description" content="${esc(meta.description)}">
  <link rel="icon" href="assets/icon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/css/site.css">
  <script type="module" src="assets/js/${meta.script}"></script>
</head>
<body class="page-${meta.nav}">
  <a class="skip" href="#main">Skip to the content</a>
  <header class="top">
    <div class="top-inner">
      <a class="mark" href="index.html" aria-label="Ringtrue home">
        <svg class="mark-bars" viewBox="0 0 36 22" aria-hidden="true"><rect x="1" y="2" width="6" height="18" rx="1.5"/><rect x="10" y="4" width="6" height="14" rx="1.5"/><rect x="19" y="6" width="6" height="10" rx="1.5"/><rect x="28" y="8" width="6" height="6" rx="1.5"/></svg>
        <span>Ringtrue</span>
      </a>
      <nav class="nav" aria-label="Pages">
        ${nav}
      </nav>
    </div>
  </header>
  <main id="main">
${body.trimEnd()}
  </main>
  <footer class="foot">
    <div class="foot-inner">
      <p>Ringtrue is open source (MIT). Everything runs in your browser: no sign-in, no tracking, and recordings never leave your device.</p>
      <p><a href="https://github.com/reihooneh/ringtrue">Source code and tests on GitHub</a></p>
    </div>
  </footer>
</body>
</html>
`;
  writeFileSync(join(root, 'site', file), html);
  built.push(file);
}
console.log(`Built ${built.length} pages (${built.join(', ')}), ${materials.length} materials, a ${set.length}-bar set, ${copies.length} vendored files.`);
